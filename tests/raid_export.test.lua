STUB.Fire("ADDON_LOADED", "LevelMates")
local _, ns = ...
STUB.guildRoles = { Tester = 2 }; ns.Roster.InvalidateGuildRoster()
STUB.Fire("PLAYER_ENTERING_WORLD", true, false); STUB.Advance(30)
local LT, E = ns.Loot, ns.LootExport
assert(LT.Post("Ana", 30, "att", 'Attendance, "quoted"', { raid = "raid1" }))
assert(LT.Post("Ana", 3, "adj", "=formula", { raid = "raid2" }))
assert(LT.Post("Ana", 1, "adj", "Unscoped"))
local award = LT.Award(9001, "Ana", { cost = 10, raid = "raid1", boss = "Boss, one" })
assert(award and LT.Cancel(award, "Cancelled"))
local rows = E.Rows("raid1")
assert(#rows == 4, "attendance, spend, cancelled award, refund all included")
local kinds = {}; for _, r in ipairs(rows) do kinds[r.record_type] = true; assert(r.raid_id == "raid1") end
assert(kinds.lk and kinds.la and #E.Raids() == 2)
local c, n = E.CSV("raid1")
assert(n == 4 and c:find('"Attendance, ""quoted"""', 1, true))
assert(c:find('"Boss, one"', 1, true) and c:find(",-10,", 1, true), "numeric negative values stay numeric")
assert(not c:find("Unscoped", 1, true) and not c:find("=formula", 1, true))
assert(E.CSV("raid2"):find('"\'=formula"', 1, true), "formula-like text is escaped")
local before = #STUB.sent
local oldBalance = LT.Balance("Ana")
assert(E.Text("raid1"):find("cancelled", 1, true) and #STUB.sent == before and LT.Balance("Ana") == oldBalance)
assert(E.CSV("raid1") == c, "deterministic export")
assert(not E.Rows("bad id") and not E.CSV(nil))
local empty, total = E.CSV("missing")
assert(total == 0 and empty:find("record_type", 1, true))
local opened
ns.DiscordCopy.OpenText = function(text) opened = text end
SlashCmdList.LEVELMATES("raidexport")
assert(opened:find("raid1", 1, true) and opened:find("raid2", 1, true))
SlashCmdList.LEVELMATES("raidexport raid1 csv")
assert(opened == c)
SlashCmdList.LEVELMATES("raidexport raid1 unknown")
assert(opened == ns.L.RAID_EXPORT_HELP)
assert(LT.Post("Bob", 10, "adj", "Reserve", { raid = "raid3" }))
local old = LT.Award(9002, "Ana", { cost = 5, raid = "raid3" })
local replacement = LT.Correct(old, "Bob", "Recipient correction")
assert(replacement)
local chain = E.Rows("raid3")
assert(#chain == 6)
local byId = {}; for _, r in ipairs(chain) do byId[r.record_id] = r end
assert(byId[old].state == "c" and byId[replacement].reference == old)
assert(byId[replacement].spend_id and byId[byId[replacement].spend_id].entry_kind == "spend")
assert(LT.Post("Ána", 1, "adj", "+formula", { raid = "unicode" }))
assert(E.CSV("unicode"):find("Ána", 1, true) and E.CSV("unicode"):find("'+formula", 1, true))
